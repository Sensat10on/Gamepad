package com.example.bluetoothgamepad.domain

object KeyboardReport {
    const val REPORT_ID=3
    const val ENTER=0x28
    const val RIGHT=0x4F
    const val LEFT=0x50
    const val DOWN=0x51
    const val UP=0x52
    val descriptor=byteArrayOf(
        0x05,0x01,0x09,0x06,0xA1.toByte(),0x01,0x85.toByte(),REPORT_ID.toByte(),
        0x05,0x07,0x19,0xE0.toByte(),0x29,0xE7.toByte(),0x15,0x00,0x25,0x01,
        0x75,0x01,0x95.toByte(),0x08,0x81.toByte(),0x02,
        0x75,0x08,0x95.toByte(),0x01,0x81.toByte(),0x03,
        0x19,0x00,0x29,0x65,0x15,0x00,0x25,0x65,
        0x75,0x08,0x95.toByte(),0x06,0x81.toByte(),0x00,0xC0.toByte()
    )
    fun encode(keyCode:Int)=byteArrayOf(0,0,keyCode.toByte(),0,0,0,0,0)
}
